            <h2 id="week" class="left-text">3.1 Weekly Change Calculation</h2>
                
            <p>
                Weekly change was calculated using the difference between the recorded weight at the start 
                of the week (Monday) and the recorded weight at the end of the week (Sunday).

                Weekly average weight was calculated separately using the average of daily 
                weight measurements across the week.

                Therefore, weekly weight change and change in weekly average weight are related 
                but not identical measures, as weekly averages smooth daily fluctuations while weekly 
                change reflects the net change across the week.
            </p>  
            
            <h1 id="what" class="left-text">4 What ?</h1>
            
            <p>
                This report uses two weight calculations based on daily weight measurements: 
                weekly average weight to observe the weekly trend, and weekly start-to-end weight change 
                to measure the short-term effect of fasting. 

                The average weight shows the direction of travel, both measurements act as a weekly feedback 
                signal. 
            </p>
            
