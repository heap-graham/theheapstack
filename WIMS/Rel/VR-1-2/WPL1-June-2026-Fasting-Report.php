            <h1 id="introduction" class="left-text"> 1 Introduction and Scope</h1>
            <p>
                           The general nutritional and fasting concepts referred to in this report were 
                           influenced by the work of Patrick Holford and Dr. Alan Goldhamer [9]. 
                           Their books provided accessible explanations of blood sugar regulation, appetite, 
                           and fasting which helped inform the interpretation of the observations 
                           in this case study. This report, however, is based on personal data and 
                           reflection rather than a formal scientific study. 
                            
                           This report describes my personal experience using fasting and gentle exercise 
                           as tools to manage my own weight. This report covers the period from 
                           September 2025 to January 2026 and is written as a reflective personal 
                           case study based on my own experience, not as a scientific study or general advice.

                            The purpose of this report is to reflect on this experience, 
                            identify what I have learnt during this period, and consider how these lessons might be useful in the future, both for myself and ideally for others.

                            This is not medical advice, and I am not directing others on what to do. 
                            
                            The author recognises that the quality and quantity of food intake 
                            can affect weight changes. 
                            
                            However in this report food considerations and calorific intake are 
                            outside the scope of this report. 
            </p>
            <h2 id="scope" class="left-text"> 1.1 Scope and terminology </h2>
            <p>
                This report is limited in scope and focuses on physical body weight changes, 
                fasting frequency, and general observations about my habits and routines during this period.
                This report does not attempt to measure or analyse medical markers such as blood sugar or 
                hormone levels and does not attempt to provide a scientific explanation of fasting or weight 
                loss.
                
                The term “fasting” is used in a simple descriptive way to describe a restricted eating pattern
                during this period. 
                The term “feasting” refers to intentional, unrestricted eating during non-fasting periods. 
                Food is eaten to satiety without consideration to the quality or quantity of food intake. 
                This report focuses on what happened during this period and what was learnt from the experience,
                rather than trying to provide general and/or specific conclusions.
                This report is based on my personal experience and measurement, informed by general reading, 
                and is not intended to be a formal literature review. 
                The aim is to keep the report readable and practical and 
                to document a lived experience rather than to summarise existing 
                technical research on the topic.
            </p>
            
            <h2 id="limits" class="left-text"> 1.2 Limitations of this Report </h2>
            
            <p>
