            <h1 id="background" class="left-text"> 2 Background</h1>
            <p>
                Weight management is often framed as a purely nutritional problem [9]. 
            
                In practice, weight management is a function of quality and quantity of food intake, 
                exercise undertaken and ones quality of life experience.
                
                Individuals who choose to manage their weight typically do so for personal reasons 
                linked to health, confidence, and/or quality of life.
                
                Sustainable change rarely occurs through the force of ones will. Positive change tends to 
                emerge from small repeatable actions. When attempting positive weight change, 
                setbacks are common. 
                
                In my experience, reframing a setback as "What difficulties were present this time?” 
                rather than as failure allows for learning and adjustment rather than "quitting".
                
                In addition, small changes to one's life are preferable and more sustainable than dramatic 
                changes; for example, a yoga pose which requires a deep stretch that feels tight today may 
                extend further tomorrow through gradual repetition. The same applies to learning new habits: 
                small, consistent, repeatable adjustments add up.
                
                For weight loss to work successfully - the process of weight loss is to considered to be a 
                feedback loop based on measurement and experience.  
                
                From a phyiscal perspective the body can use both sugar (glucose) and stored fat 
                (converted to ketones) as fuel sources to create the energy needed to sustain daily living.
                
                This fat conversion to ketones as an alternative fuel source to glucose can occur either 
                through a calorie deficit with a restricted food intake or through fasting by taking 
                in zero or minimal calories. 
                
                We all fast while sleeping and naturally move to a fat-burning state while our blood sugar 
                is low.  
                
                Modern eating patterns, particularly the frequent consumption of refined carbohydrates 
                and processed foods, may reduce the amount of time spent in fat-burning states.
                
                Typically, while in a fat-burning state, blood sugar is low, insulin levels are low, 
                and stored energy begins to be accessed by the conversion of fat to ketones; 
                regular fasting extends the period of low blood sugar and low insulin release.
                
                Energy balance remains fundamental to weight loss; simplistically, fewer calories in than 
                the energy required to maintain our bodies during the day leads to a calorie deficit 
                and a reduction in weight, namely fat loss.
                
                For this reporting period, fasting provided a method that made calorie deficit easier 
                to sustain. essentially there is little mental effort required to stop eating food, 
                as apposed to traditional calorie-restrictive diets which needs one to pay constant 
                attention to the quality and quantity of food intake. 
                
                I also note that my own weight gain has been influenced by comfort eating: 
                using sugar, fat, and salt to produce short-term pleasure or emotional relief [9]. 
                
                Measurement of my daily weight changes increased my awareness of my food intake, 
                when not fasting and that awareness helped me to understand better how my eating habits influence my weight. 
            </p>
            
            <h1 id="method" class="left-text">3 Method &amp; Constraints </h1>
            
            <p>
                My weight was recorded daily in a spreadsheet and summarised using weekly averages and 
                compared to planned weekly targets; initially a weight loss of one to two pounds per 
                week was considered to be an achievable and sustainable target. 

                Morning weight serves as my first point of measurement, which I refer to as my rested weight. 
                This is the weight we have when we wake up from sleep, and have not taken breakfast.

                Weight change is reviewed on a weekly basis rather than focusing on fluctuating daily changes. 

                The aim was to observe the weekly average weight trend rather than focus on day-to-day 
                fluctuations.

                Fasting patterns varied week to week, typically ranging between one and four fasting days per week. 

                Fasting is used as a simple and  practical way to reduce overall food intake and simplify daily 
                food preparation decisions, rather than as a strict calorie-deficient-based dietary system.

                In assessing a "fasting day", I have learnt from experience that better results can be obtained 
                by sleeping through a 24-hour fast, so, for example, if I stop eating on a Monday evening at 6 pm, 
                then my fasting day is Tuesday, and I do not break the fast typically until after 6 am on the 
                Wednesday morning, sometimes later – as the longer I prolong the fast, the better the results are.  

                So a one-day fast is counted as a minimal 36-hour fast rather than a 24-hour fast and must 
                include at least one night's sleep. 

                In my opinion, the most significant effects of fasting occur while we are sleeping. 

                Exercise during this period was generally gentle and sustained (walking, housework, hobbies), 
                rather than intense exercise training. 

                The focus was on maintaining regular movement over a period of one or two hours, 
                rather than undertaking intensive exercise sessions.

                December 2025 represents a pause in weight measurement. This period effectively acted as a break 
                from active weight management. January 2026 marks a return to weight measurement and tracking. 

                The remainder of this report is structured using a simple reflective framework commonly 
                used in education and psychology: What? So What? What Next?:
            </p>
            
